/**
 * 协议版本号。
 *
 * 客户端在 `session:hello` 里报自己编译进去的这个数，服务端拿它和自己这份比，
 * 对不上就回一条 `session:rejected`（reason 为 `'protocol-version'`）再关连接
 * （《正式版架构》5.5）。界面据此提示「请刷新页面」，
 * 而不是让玩家对着一局收不到事件的对战干等。
 *
 * **什么时候要 +1**：任何一条消息的形状发生了不兼容的变化——加必填字段、改字段类型、
 * 删一种消息、改一个 `type` 字符串。加一个可选字段、或者整加一种新消息不用动它：
 * 服务端发给客户端的消息是宽松解析的（多出来的字段被丢掉，见 index.ts），
 * 老客户端不会因为这些而炸。
 *
 * **为什么版本号不写进 WebSocket 子协议名**（子协议是 `ai-duel`，不带版本，见 handshake.ts）：
 * 写进去的话版本不对的客户端在升级握手那一步就被浏览器判失败，
 * 而浏览器拿不到失败握手的响应体，玩家只会看到一个没有细节的 error。
 * 放在第一条消息里，服务端才有机会把中文原因说清楚。
 *
 * 项目还没上线、不留兼容层（见 AGENTS.md），所以永远只有一个当前值，
 * 不存在「服务端同时支持 v1 和 v2」这回事。
 */
export const PROTOCOL_VERSION = 2
